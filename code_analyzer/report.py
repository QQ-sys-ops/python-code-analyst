def _section_9(structure, lang="en") -> str:
    """九、文档覆盖率"""
    lines = [f"## {_t('九、文档覆盖率', lang)}\n"]

    total = len(structure.all_functions)
    documented = sum(1 for f in structure.all_functions if f.docstring and f.docstring_length > 10)
    coverage = (documented / total * 100) if total > 0 else 100

    lines.append(f"| {_t('指标', lang)} | {_t('数值', lang)} |")
    lines.append(f"|------|------|")
    lines.append(f"| {_t('总函数/方法', lang)} | {total} |")
    lines.append(f"| {_t('有docstring', lang)} | {documented} |")
    lines.append(f"| **{_t('覆盖率', lang)}** | **{coverage:.1f}%** |")

    # 缺失docstring的方法
    missing = [f for f in structure.all_functions if not f.docstring or f.docstring_length <= 10]
    if missing:
        lines.append(f"\n### {_t('缺失docstring的方法', lang)}\n")
        lines.append(f"| {_t('函数', lang)} | {_t('位置', lang)} | {_t('优先级', lang)} |")
        lines.append(f"|------|------|--------|")
        for f in missing[:15]:
            grade = _complexity_grade(f.cyclomatic_complexity)
            priority = "P0" if grade in ("D", "F") else "P1" if grade == "C" else "P2"
            lines.append(f"| `{f.qualified_name}` | L{f.lineno} | {priority} |")
        if len(missing) > 15:
            lines.append(f"\n*（{_t('仅显示前', lang)}15{_t('共', lang)}{len(missing)}个缺失）*")

    return "\n".join(lines)


def _section_10(structure, call_graph, dead_code, dependency, lang="en") -> str:
    """十、重构建议"""
    lines = [f"## {_t('十、重构建议', lang)}\n"]

    suggestions_p0 = []
    suggestions_p1 = []

    # P0: 高复杂度函数
    for f in structure.all_functions:
        if f.cyclomatic_complexity > 20:
            suggestions_p0.append(
                f"{_t('函数', lang)} `{f.qualified_name}` {_t('圈复杂度', lang)}{f.cyclomatic_complexity}(D级)，{_t('建议拆分', lang)}"
            )
        elif f.cyclomatic_complexity > 10:
            suggestions_p1.append(
                f"{_t('函数', lang)} `{f.qualified_name}` {_t('圈复杂度', lang)}{f.cyclomatic_complexity}(C级)，{_t('可考虑简化', lang)}"
            )

    # P0: 死代码
    for func in dead_code.unreachable:
        suggestions_p1.append(f"{_t('函数', lang)} `{func}` {_t('无调用路径，可考虑移除或添加入口', lang)}")

    # P1: 循环依赖
    if dependency.has_circular:
        for cycle in dependency.circular_cycles:
            suggestions_p0.append(f"{_t('循环导入', lang)}: {' → '.join(cycle)}，{_t('需重构依赖方向', lang)}")

    # P1: 无docstring的复杂函数
    for f in structure.all_functions:
        if (not f.docstring or f.docstring_length <= 10) and f.cyclomatic_complexity > 5:
            suggestions_p1.append(
                f"{_t('函数', lang)} `{f.qualified_name}` {_t('复杂度', lang)}{f.cyclomatic_complexity}{_t('复杂度但无docstring', lang)}"
            )

    if suggestions_p0:
        lines.append(f"### P0级（{_t('建议立即修复', lang)}）\n")
        lines.append(f"| # | {_t('建议', lang)} |")
        lines.append("|---|------|")
        for i, s in enumerate(suggestions_p0, 1):
            lines.append(f"| {i} | {s} |")

    if suggestions_p1:
        lines.append(f"\n### P1级（{_t('建议后续优化', lang)}）\n")
        lines.append(f"| # | {_t('建议', lang)} |")
        lines.append("|---|------|")
        for i, s in enumerate(suggestions_p1[:10], 1):
            lines.append(f"| {i} | {s} |")

    if not suggestions_p0 and not suggestions_p1:
        lines.append(f"✅ {_t('未发现需要重构的问题', lang)}。")

    return "\n".join(lines)


def _section_11(structure, call_graph, dead_code, dependency, lang="en") -> str:
    """十一、综合评估"""
    lines = [f"## {_t('十一、综合评估', lang)}\n"]

    # 各维度评分 (0-10)
    # 复杂度: 平均CC越低越好
    avg_cc = structure.avg_complexity
    complexity_score = max(0, min(10, 10 - avg_cc))

    # 文档: 覆盖率越高越好
    doc_score = structure.doc_coverage / 10

    # 结构: 函数数量合理+类结构清晰
    struct_score = 7.0  # 基础分
    if structure.class_count > 0 and structure.method_count > 0:
        struct_score += 1  # 有类结构
    if structure.function_count + structure.method_count < 50:
        struct_score += 1  # 规模合理
    struct_score = min(10, struct_score)

    # 死代码: 覆盖率越高越好
    dead_score = dead_code.coverage / 10

    # 依赖: 无循环+合理分类
    dep_score = 8.0
    if dependency.has_circular:
        dep_score -= 3
    if len(dependency.third_party) > 10:
        dep_score -= 1
    dep_score = max(0, dep_score)

    # 综合分
    weights = {"complexity": 0.25, "doc": 0.25, "structure": 0.2,
               "dead_code": 0.15, "dependency": 0.15}
    total = (
        complexity_score * weights["complexity"]
        + doc_score * weights["doc"]
        + struct_score * weights["structure"]
        + dead_score * weights["dead_code"]
        + dep_score * weights["dependency"]
    )

    grade = "A" if total >= 8.5 else "B" if total >= 7 else "C" if total >= 5.5 else "D" if total >= 4 else "F"

    lines.append(f"| {_t('维度', lang)} | {_t('得分', lang)} | {_t('权重', lang)} | {_t('说明', lang)} |")
    lines.append("|------|:----:|:----:|------|")
    lines.append(f"| {_t('复杂度', lang)} | {complexity_score:.1f} | 25% | {_t('平均', lang)}CC={avg_cc:.1f} |")
    lines.append(f"| {_t('文档', lang)} | {doc_score:.1f} | 25% | {_t('覆盖率', lang)}={structure.doc_coverage:.1f}% |")
    lines.append(f"| {_t('结构', lang)} | {struct_score:.1f} | 20% | {_t('类数量', lang)}{structure.class_count}个+{_t('函数数量', lang)}{structure.function_count}个 |")
    lines.append(f"| {_t('死代码', lang)} | {dead_score:.1f} | 15% | {_t('覆盖率', lang)}={dead_code.coverage:.1f}% |")
    lines.append(f"| {_t('依赖', lang)} | {dep_score:.1f} | 15% | {_t('循环导入', lang)}={dependency.has_circular} |")
    lines.append(f"| **{_t('综合', lang)}** | **{total:.1f}** | **100%** | **{grade}级** |")

    return "\n".join(lines)


def _section_12(structure, call_graph, dead_code, lang="en") -> str:
    """十二、总结"""
    lines = [f"## {_t('十二、总结', lang)}\n"]

    # 优势
    strengths = []
    if structure.avg_complexity <= 5:
        strengths.append("整体复杂度低，代码可读性好" if lang == "zh" else "Low overall complexity, good code readability")
    if structure.doc_coverage >= 80:
        strengths.append("文档覆盖率高" if lang == "zh" else "High documentation coverage")
    if not dead_code.unreachable:
        strengths.append("无死代码，所有函数均有调用路径" if lang == "zh" else "No dead code, all functions have call paths")
    if call_graph.max_depth <= 3:
        strengths.append("调用层次浅，结构清晰" if lang == "zh" else "Shallow call depth, clear structure")

    # 问题
    issues = []
    high_cc = [f for f in structure.all_functions if f.cyclomatic_complexity > 10]
    if high_cc:
        issues.append(f"{len(high_cc)}个函数复杂度>10，需关注" if lang == "zh" else f"{len(high_cc)} functions with complexity>10, needs attention")
    if dead_code.unreachable:
        issues.append(f"{len(dead_code.unreachable)}个函数无调用路径" if lang == "zh" else f"{len(dead_code.unreachable)} functions with no call path")
    if structure.doc_coverage < 50:
        issues.append("文档覆盖率不足50%" if lang == "zh" else "Documentation coverage below 50%")

    lines.append(f"| {_t('优势', lang)} | {_t('问题', lang)} |")
    lines.append("|------|------|")

    max_rows = max(len(strengths), len(issues))
    for i in range(max_rows):
        s = f"✅ {strengths[i]}" if i < len(strengths) else ""
        issue = f"⚠️ {issues[i]}" if i < len(issues) else ""
        lines.append(f"| {s} | {issue} |")

    if not strengths and not issues:
        lines.append(f"| ✅ {_t('无明显问题', lang)} | ⚠️ {_t('无明显优势', lang)} |")

    # 整体评价
    total_funcs = len(structure.all_functions)
    total_lines = structure.total_lines
    lines.append(f"\n**{_t('整体评价', lang)}**: {total_lines}行代码，{structure.class_count}个类，"
                  f"{total_funcs}个函数/方法，{_t('复杂度', lang)}{_t('平均', lang)}{structure.avg_complexity:.1f}")

    return "\n".join(lines)
