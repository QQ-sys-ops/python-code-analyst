def _t(key: str, lang: str = "en") -> str:
    """Look up a translation key. Returns the key itself if not found."""
    return TRANSLATIONS.get(lang, TRANSLATIONS["en"]).get(key, key)


# 复杂度等级映射
def _complexity_grade(cc: int) -> str:
    if cc <= 5:
        return "A"
    elif cc <= 10:
        return "B"
    elif cc <= 20:
        return "C"
    elif cc <= 50:
        return "D"
    else:
        return "F"


def _grade_color(grade: str) -> str:
    return {"A": "✅", "B": "✅", "C": "⚠️", "D": "🔴", "F": "💀"}.get(grade, "❓")


def generate_report(
    structure,
    call_graph,
    impact_analysis,
    dead_code_result,
    dependency_result,
    ai_analysis: dict = None,
    lang: str = "en",
) -> str:
    """
    生成12节标准报告

    Args:
        structure: StructureAnalysis
        call_graph: CallGraph
        impact_analysis: ImpactAnalysis
        dead_code_result: DeadCodeResult
        dependency_result: DependencyInfo
        ai_analysis: Agent层分析结果（可选）
        lang: Report language ('en' or 'zh'), default 'en'
    """
    now = datetime.now().strftime("%Y-%m-%d %H:%M")
    filename = structure.file_path

    sections = []

    # ═══ 一、结构概览 ═══
    sections.append(_section_1(structure, lang))

    # ═══ 二、架构分析 ═══
    sections.append(_section_2(structure, lang))

    # ═══ 三、复杂度分析 ═══
    sections.append(_section_3(structure, lang))

    # ═══ 四、调用图分析 ═══
    sections.append(_section_4(call_graph, lang))

    # ═══ 五、影响面分析 ═══
    sections.append(_section_5(impact_analysis, lang))

    # ═══ 六、死代码检测 ═══
    sections.append(_section_6(dead_code_result, lang))

    # ═══ 七、依赖分析 ═══
    sections.append(_section_7(dependency_result, lang))

    # ═══ 八、代码意图（Agent层） ═══
    sections.append(_section_8(ai_analysis, lang))

    # ═══ 九、文档覆盖率 ═══
    sections.append(_section_9(structure, lang))

    # ═══ 十、重构建议 ═══
    sections.append(_section_10(structure, call_graph, dead_code_result, dependency_result, lang))

    # ═══ 十一、综合评估 ═══
    sections.append(_section_11(structure, call_graph, dead_code_result, dependency_result, lang))

    # ═══ 十二、总结 ═══
    sections.append(_section_12(structure, call_graph, dead_code_result, lang))

    # 组装报告
    header = f"""# {filename} {_t('深度分析报告', lang)}

**{_t('分析时间', lang)}**: {now}
**{_t('分析工具', lang)}**: python-code-analyst v2.0.0
**{_t('文件路径', lang)}**: `{filename}`

---"""

    footer = f"""
---

*{_t('分析报告生成时间', lang)}: {now}*
*{_t('分析工具', lang)}: python-code-analyst v2.0.0*
*⚠️ {_t('本报告由code_analyzer工具自动生成', lang)}，{_t('Agent层分析由LLM完成', lang)}*"""

    return header + "\n\n".join(sections) + footer


def _section_1(structure, lang="en") -> str:
    """一、结构概览"""
    # 计算综合评分
    grades = []
    for f in structure.all_functions:
        g = _complexity_grade(f.cyclomatic_complexity)
        grades.append(g)

    grade_counts = {}
    for g in grades:
        grade_counts[g] = grade_counts.get(g, 0) + 1

    grade_str = " ".join(f"{g}:{grade_counts.get(g,0)}" for g in "ABCDF" if g in grade_counts)

    return f"""## {_t('一、结构概览', lang)}

| {_t('维度', lang)} | {_t('说明', lang)} | {_t('说明', lang)} |
|------|------|------|
| {_t('总行数', lang)} | {structure.total_lines}行 | {_t('包含空行', lang)} |
| {_t('有效代码行(SLOC)', lang)} | {structure.sloc}行 | {_t('有效语句', lang)} |
| {_t('类数量', lang)} | {structure.class_count}个 | |
| {_t('函数数量', lang)} | {structure.function_count}个 | {_t('模块级', lang)} |
| {_t('方法数量', lang)} | {structure.method_count}个 | {_t('含继承方法', lang)} |
| {_t('导入数量', lang)} | {structure.import_count}个 | |
| {_t('参数总数', lang)} | {structure.total_arguments}个 | |

**{_t('复杂度分布', lang)}**: {grade_str}"""


def _section_2(structure, lang="en") -> str:
    """二、架构分析"""
    lines = [f"## {_t('二、架构分析', lang)}\n"]

    if structure.classes:
        lines.append(f"### {_t('类结构', lang)}\n")
        for cls in structure.classes:
            bases = ", ".join(cls.bases) if cls.bases else _t("无", lang)
            methods = ", ".join(m.name for m in cls.methods[:10])
            if cls.method_count > 10:
                methods += f" ... ({_t('共', lang)}{cls.method_count}个)"
            lines.append(f"**{cls.name}** ({_t('继承', lang)}: {bases})")
            lines.append(f"- {_t('方法', lang)}: {methods}")
            lines.append("")

    # 设计模式推断
    lines.append(f"### {_t('设计模式推断', lang)}\n")
    patterns = []
    for cls in structure.classes:
        method_names = [m.name for m in cls.methods]
        if '__init__' in method_names and len(cls.bases) == 0:
            patterns.append(f"- {cls.name}: {_t('基础类', lang)}")
        elif any(m.is_classmethod for m in cls.methods):
            patterns.append(f"- {cls.name}: {_t('含类方法（可能的工厂/注册模式）', lang)}")
        elif any(m.is_staticmethod for m in cls.methods):
            patterns.append(f"- {cls.name}: {_t('含静态方法（工具类）', lang)}")

    if patterns:
        lines.extend(patterns)
    else:
        lines.append(f"- {_t('未检测到明显的设计模式', lang)}")

    return "\n".join(lines)


def _section_3(structure, lang="en") -> str:
    """三、复杂度分析"""
    lines = [f"## {_t('三、复杂度分析', lang)}\n"]
    lines.append(f"| {_t('类/方法', lang)} | {_t('位置', lang)} | {_t('圈复杂度', lang)} | {_t('认知复杂度', lang)} | {_t('行数', lang)} | {_t('评级', lang)} |")
    lines.append("|---------|------|:---:|:---:|:---:|:---:|")

    for f in structure.all_functions:
        grade = _complexity_grade(f.cyclomatic_complexity)
        icon = _grade_color(grade)
        loc = f"L{f.lineno}" if f.lineno else "?"
        qn = f.qualified_name
        lines.append(
            f"| {qn} | {loc} | {f.cyclomatic_complexity} | "
            f"{f.cognitive_complexity} | {f.line_count} | {icon}{grade} |"
        )

    # 整体评级
    ccs = [f.cyclomatic_complexity for f in structure.all_functions]
    if ccs:
        avg_cc = sum(ccs) / len(ccs)
        max_cc = max(ccs)
        grade_counts = {}
        for cc in ccs:
            g = _complexity_grade(cc)
            grade_counts[g] = grade_counts.get(g, 0) + 1
        dominant = max(grade_counts, key=grade_counts.get)
        lines.append(f"\n**{_t('整体评级', lang)}**: {dominant}级 "
                      f"({grade_counts.get(dominant,0)}个, "
                      f"{grade_counts.get(dominant,0)/len(ccs)*100:.0f}%) "
                      f"| {_t('平均', lang)}: {avg_cc:.1f} | {_t('最大', lang)}: {max_cc}")

    return "\n".join(lines)


def _section_4(call_graph, lang="en") -> str:
    """四、调用图分析"""
    lines = [f"## {_t('四、调用图分析', lang)}\n"]

    lines.append(f"**{_t('调用边', lang)}**: {len(call_graph.edges)}条  ")
    lines.append(f"**{_t('用户定义函数', lang)}**: {len(call_graph.user_functions)}个  ")
    lines.append(f"**{_t('被调用函数', lang)}**: {len(call_graph.called_functions)}个  ")
    lines.append(f"**{_t('最大调用深度', lang)}**: {call_graph.max_depth}\n")

    # 调用关系表
    if call_graph.edges:
        lines.append(f"### {_t('调用关系', lang)}\n")
        lines.append(f"| {_t('调用者', lang)} | {_t('被调用者', lang)} | {_t('行号', lang)} |")
        lines.append("|--------|----------|------|")
        for e in call_graph.edges[:30]:  # 限制显示数量
            lines.append(f"| {e.caller} | {e.callee} | L{e.lineno} |")
        if len(call_graph.edges) > 30:
            lines.append(f"\n*（{_t('仅显示前', lang)}30{_t('共', lang)}{len(call_graph.edges)}条）*")

    # 入口点
    if call_graph.entry_points:
        lines.append(f"\n### {_t('入口点', lang)}\n")
        for ep in call_graph.entry_points:
            lines.append(f"- `{ep}`")

    return "\n".join(lines)


def _section_5(impact_analysis, lang="en") -> str:
    """五、影响面分析"""
    lines = [f"## {_t('五、影响面分析', lang)}\n"]

    if impact_analysis.impacts:
        lines.append(f"| {_t('修改目标', lang)} | {_t('直接影响', lang)} | {_t('间接影响', lang)} | {_t('总影响', lang)} |")
        lines.append("|----------|:--------:|:--------:|:------:|")
        for imp in impact_analysis.impacts[:20]:
            lines.append(
                f"| {imp.function} | {len(imp.direct_impact)} | "
                f"{len(imp.indirect_impact)} | **{imp.total_impact}** |"
            )
    else:
        lines.append(_t("无调用关系，影响面分析不适用", lang) + "。")

    return "\n".join(lines)


